"""Project 2026-27 games played and write config/games_played.yaml.

Replaces the flat default of 82 (spec §3.5 left GP as a hand-edited config).
Every player had been projected at 82 except the hand-reviewed Lakers, which
overstated availability for everyone and hid the single biggest driver of a
high-floor draft: who actually plays.

Model (chosen by backtest, 2026-10-14 -- train on 2023-24 + 2024-25, predict
2025-26 games for the 178 players with 1,500+ minutes in 2024-25):

    hist = weighted mean of games played in the seasons a player appeared,
           weights 0.5 / 0.3 / 0.2 (2025-26 / 2024-25 / 2023-24), renormalised
           over the seasons present -- a season missed entirely to injury is
           absent, not zero, and the return is handled in config/injuries.yaml
    gp   = 0.5 * hist + 0.5 * 62 - 1.0 * max(age - 30, 0)
    gp   = gp * (82 - games_missed) / 82, capped by any gp_cap   [injuries.yaml]
    clipped to [10, 78]

Backtest MAE (games): flat 82 -> 25.1, last season -> 18.0, this -> 15.8.
Games played is mostly unpredictable from history (an OLS with history, age
and minutes reaches R^2 0.04), so the model shrinks hard toward the mean.
That is the honest answer: history moves a projection by a few games, not by
twenty, and a known injury is worth far more than a reputation.

Entries marked `estimated: false` (hand-reviewed -- currently the Lakers) are
kept exactly as they are. Hand review outranks a generated value.

Usage: python scripts/project_games_played.py
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]
CANON = ROOT / "data" / "canonical"
CONFIG = ROOT / "config"
REPORTS = ROOT / "reports"

SEASON_WEIGHTS = {"2025-26": 0.5, "2024-25": 0.3, "2023-24": 0.2}
SHRINK = 0.5
PRIOR_GP = 62.0
AGE_PENALTY_PER_YEAR = 1.0
AGE_PENALTY_FROM = 30
GP_MIN, GP_MAX = 10, 78
NO_HISTORY_GP = 60  # roster players with a player_id but no games in the window


def history_gp(rows: pd.DataFrame, exclude: set[str]) -> float | None:
    rows = rows[~rows["season"].isin(exclude) & rows["season"].isin(SEASON_WEIGHTS)]
    if rows.empty:
        return None
    w = rows["season"].map(SEASON_WEIGHTS)
    return float((rows["g"] * w).sum() / w.sum())


def project(rosters: pd.DataFrame, player_seasons: pd.DataFrame, injuries: dict) -> pd.DataFrame:
    matched = rosters.dropna(subset=["player_id"]).drop_duplicates("player_id")
    by_player = dict(tuple(player_seasons.groupby("player_id")))
    out = []
    for _, r in matched.iterrows():
        pid = r["player_id"]
        inj = injuries.get(pid, {}) or {}
        hist = history_gp(by_player.get(pid, player_seasons.iloc[0:0]), set(inj.get("exclude_seasons", [])))
        age = r["age_at_season_start"]
        if hist is None:
            base = NO_HISTORY_GP
        else:
            base = (1 - SHRINK) * hist + SHRINK * PRIOR_GP
        base -= AGE_PENALTY_PER_YEAR * max(age - AGE_PENALTY_FROM, 0)
        missed = inj.get("games_missed", 0)
        gp = base * (82 - missed) / 82
        if "gp_cap" in inj:
            gp = min(gp, inj["gp_cap"])
        gp = max(GP_MIN, min(GP_MAX, gp)) if missed < 82 else 0
        out.append({
            "player_id": pid, "team": r["team"], "player": r["roster_name"], "age": age,
            "hist_gp": None if hist is None else round(hist, 1),
            "base_gp": round(base, 1), "games_missed": missed, "gp_cap": inj.get("gp_cap"),
            "gp": int(round(gp)), "injury_note": inj.get("note", ""),
        })
    return pd.DataFrame(out)


def main() -> None:
    rosters = pd.read_csv(CANON / "rosters_2627.csv")
    player_seasons = pd.read_csv(CANON / "player_seasons.csv")
    inj_doc = yaml.safe_load((CONFIG / "injuries.yaml").read_text(encoding="utf-8"))
    injuries = inj_doc.get("injuries", {})

    unknown = sorted(set(injuries) - set(rosters["player_id"].dropna()))
    if unknown:
        raise SystemExit(f"injuries.yaml names player_ids not on any roster: {unknown}")

    proj = project(rosters, player_seasons, injuries)

    gp_path = CONFIG / "games_played.yaml"
    existing = yaml.safe_load(gp_path.read_text(encoding="utf-8")).get("games_played", {})
    kept = {pid: v for pid, v in existing.items() if v.get("estimated") is False}

    doc = {}
    for _, row in proj.sort_values("player_id").iterrows():
        pid = row["player_id"]
        if pid in kept:
            doc[pid] = kept[pid]
        else:
            doc[pid] = {"estimated": True, "gp": int(row["gp"])}
    for pid, v in kept.items():  # hand-reviewed entries never dropped
        doc.setdefault(pid, v)

    header = (
        "# Generated by scripts/project_games_played.py (history + age + config/injuries.yaml).\n"
        "# `estimated: false` entries are hand-reviewed and are never overwritten by the script.\n"
    )
    gp_path.write_text(header + yaml.safe_dump({"games_played": doc}, sort_keys=True), encoding="utf-8")

    proj["kept_hand_value"] = proj["player_id"].isin(kept)
    proj.loc[proj["kept_hand_value"], "gp"] = proj.loc[proj["kept_hand_value"], "player_id"].map(
        lambda p: kept[p]["gp"])
    REPORTS.mkdir(exist_ok=True)
    proj.sort_values("gp").to_csv(REPORTS / "games_played_projection.csv", index=False)
    print(f"wrote {gp_path} ({len(doc)} players, {len(kept)} hand-reviewed kept)")
    print(proj["gp"].describe().round(1).to_string())


if __name__ == "__main__":
    main()
